"""LS-DYNA ``.k`` / ``.key`` mesh writer preserving parts and named sets.

Emits ``*KEYWORD``, ``*PART``, ``*NODE``, ``*ELEMENT_SOLID``,
``*SET_NODE_LIST_TITLE``, ``*SET_SOLID_TITLE``, ``*SET_SEGMENT_TITLE``, and
``*END`` matching :func:`wht_iga.meshio_ext.read_k.read_k`.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from wht_iga.meshio_ext.model import HEX8_FACES, TET4_FACES, WEDGE6_FACES, MeshModel
from wht_iga.meshio_ext.write_inp import _merge_extra_sets
from wht_iga.meshio_ext.write_rad import _wrap_space_ids

_FACE_DEF_MAP = {
    "hex8": HEX8_FACES,
    "hex20": HEX8_FACES,
    "tet4": TET4_FACES,
    "tet10": TET4_FACES,
    "wedge6": WEDGE6_FACES,
}


def write_k(
    model: MeshModel,
    path: str | Path,
    extra_sets: Any = None,
) -> Path:
    """Write a :class:`MeshModel` to an LS-DYNA ``.k`` keyword file.

    Parameters
    ----------
    model:
        Mesh model to serialize (0-based node/element indices become 1-based).
    path:
        Output ``.k`` / ``.key`` file path.
    extra_sets:
        Optional ``SetRegistry`` or iterable of ``SelectionSet`` items.

    Returns
    -------
    Path
        Written output file path.
    """
    out = Path(path)
    out.parent.mkdir(parents=True, exist_ok=True)

    node_sets, elem_sets = _merge_extra_sets(model.node_sets, model.elem_sets, extra_sets)

    elem_records: list[tuple[int, int, str, list[int]]] = []
    part_ids_seen: list[int] = []
    cursor = 0
    for block in model.blocks:
        if block.elem_type not in _FACE_DEF_MAP:
            raise ValueError(f"Unsupported element type for LS-DYNA .k: {block.elem_type!r}")
        if block.part_id not in part_ids_seen:
            part_ids_seen.append(block.part_id)
        for row in block.conn:
            cursor += 1
            elem_records.append(
                (cursor, int(block.part_id), block.elem_type, [int(n) + 1 for n in row])
            )

    lines: list[str] = [
        "*KEYWORD",
        f"$ Generated by WHT_IGA meshio_ext.write_k (unit_system={model.unit_system})",
    ]

    for pid in sorted(set(part_ids_seen) | set(model.parts.keys())):
        pname = model.parts.get(pid, f"PART-{pid}")
        lines.append("*PART")
        lines.append(f"{pid} {pid} {pid}")
        lines.append(pname)

    lines.append("*NODE")
    for idx, xyz in enumerate(model.nodes):
        lines.append(f"{idx + 1} {xyz[0]:.17g} {xyz[1]:.17g} {xyz[2]:.17g}")

    lines.append("*ELEMENT_SOLID")
    for eid, pid, _canon, conn1 in elem_records:
        lines.append(f"{eid} {pid} " + " ".join(str(n) for n in conn1))

    for sname, nids in node_sets.items():
        lines.append("*SET_NODE_LIST_TITLE")
        lines.append(sname)
        lines.extend(_wrap_space_ids((int(n) + 1 for n in nids), per_line=8))

    for sname, eids in elem_sets.items():
        lines.append("*SET_SOLID_TITLE")
        lines.append(sname)
        lines.extend(_wrap_space_ids((int(e) + 1 for e in eids), per_line=8))

    for sname, pairs in model.face_sets.items():
        lines.append("*SET_SEGMENT_TITLE")
        lines.append(sname)
        for ge, lf in pairs:
            if 0 <= ge < len(elem_records):
                _eid, _pid, canon, conn1 = elem_records[ge]
                faces_tbl = _FACE_DEF_MAP.get(canon, ())
                if 0 <= lf < len(faces_tbl):
                    fnodes = [conn1[m] for m in faces_tbl[lf]]
                    if len(fnodes) == 3:
                        fnodes = [fnodes[0], fnodes[1], fnodes[2], fnodes[2]]
                    lines.append(" ".join(str(n) for n in fnodes))

    lines.append("*END")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


__all__ = ["write_k"]
