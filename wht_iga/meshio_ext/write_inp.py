"""Abaqus ``.inp`` mesh writer preserving parts, node/elem sets, and element surfaces.

Matches :func:`wht_iga.meshio_ext.read_inp.read_inp` conventions 1-for-1 for
lossless roundtrips of ``nodes``, ``blocks``, ``parts``, ``node_sets``,
``elem_sets``, and ``face_sets`` (``*SURFACE, TYPE=ELEMENT, NAME=...``).
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping
from pathlib import Path
from typing import Any

from wht_iga.meshio_ext.model import MeshModel

CANONICAL_TO_INP: dict[str, str] = {
    "hex8": "C3D8",
    "tet4": "C3D4",
    "tet10": "C3D10",
    "hex20": "C3D20",
    "wedge6": "C3D6",
}

# Canonical local_face index (HEX8_FACES / TET4_FACES / WEDGE6_FACES) -> Abaqus S<k>.
_LF_TO_INP_SURFACE: dict[str, dict[int, int]] = {
    "hex8": {0: 1, 1: 2, 2: 6, 3: 4, 4: 3, 5: 5},
    "hex20": {0: 1, 1: 2, 2: 6, 3: 4, 4: 3, 5: 5},
    "tet4": {0: 1, 1: 2, 2: 3, 3: 4},
    "tet10": {0: 1, 1: 2, 2: 3, 3: 4},
    "wedge6": {0: 1, 1: 2, 2: 3, 3: 5, 4: 4},
}


def _wrap_ids(ids: Iterable[int], per_line: int = 16) -> list[str]:
    items = [str(int(i)) for i in ids]
    return [", ".join(items[k : k + per_line]) for k in range(0, len(items), per_line)]


def _merge_extra_sets(
    node_sets: dict[str, list[int]],
    elem_sets: dict[str, list[int]],
    extra_sets: Any,
) -> tuple[dict[str, list[int]], dict[str, list[int]]]:
    """Merge optional ``SetRegistry`` or iterable of ``SelectionSet`` objects."""
    if extra_sets is None:
        return node_sets, elem_sets
    ns = {k: list(v) for k, v in node_sets.items()}
    es = {k: list(v) for k, v in elem_sets.items()}
    items = extra_sets.items() if hasattr(extra_sets, "items") else extra_sets
    for entry in items:
        if isinstance(entry, tuple) and len(entry) == 2:
            fallback_name, s = entry
        else:
            fallback_name, s = "", entry
        name = getattr(s, "name", "") or str(fallback_name)
        kind = getattr(s, "kind", "")
        ids = getattr(s, "ids", ())
        if not name:
            continue
        if kind == "node":
            ns[name] = [int(i) for i in ids]
        elif kind == "element":
            es[name] = [int(i) for i in ids]
    return ns, es


def write_inp(
    model: MeshModel,
    path: str | Path,
    extra_sets: Any = None,
    result_fields: Mapping[str, Any] | None = None,
) -> Path:
    """Write a :class:`MeshModel` to an Abaqus ``.inp`` ASCII file.

    Parameters
    ----------
    model:
        Mesh model to serialize (all 0-based node/elem IDs are emitted 1-based).
    path:
        Output ``.inp`` file path.
    extra_sets:
        Optional ``SetRegistry`` or sequence of ``SelectionSet`` items (``"node"``
        or ``"element"``) to merge into ``*NSET`` / ``*ELSET``.
    result_fields:
        Optional comment-tagged auxiliary field metadata (never interpreted as loads/BCs).

    Returns
    -------
    Path
        Written output file path.
    """
    out = Path(path)
    out.parent.mkdir(parents=True, exist_ok=True)

    node_sets, elem_sets = _merge_extra_sets(model.node_sets, model.elem_sets, extra_sets)

    # Track global 0-based element index -> (1-based file elem ID, canonical type)
    elem_canon: list[str] = []
    block_ranges: list[tuple[int, str, Any, int]] = []  # (part_id, elem_type, conn, start_ge)
    cursor = 0
    for block in model.blocks:
        if block.elem_type not in CANONICAL_TO_INP:
            raise ValueError(f"Unsupported element type for Abaqus .inp: {block.elem_type!r}")
        n_b = int(block.conn.shape[0])
        block_ranges.append((block.part_id, block.elem_type, block.conn, cursor))
        elem_canon.extend([block.elem_type] * n_b)
        cursor += n_b

    lines: list[str] = [
        "** Generated by WHT_IGA meshio_ext.write_inp",
        f"** unit_system={model.unit_system}",
        "*NODE",
    ]
    for idx, xyz in enumerate(model.nodes):
        lines.append(f"{idx + 1}, {xyz[0]:.17g}, {xyz[1]:.17g}, {xyz[2]:.17g}")

    # Group blocks by part_id preserving sorted part order so part_ids roundtrip consistently.
    part_ids_ordered: list[int] = []
    for pid, _et, _c, _s in block_ranges:
        if pid not in part_ids_ordered:
            part_ids_ordered.append(pid)

    for pid in part_ids_ordered:
        pname = model.parts.get(pid, f"PART-{pid}")
        lines.append(f"*PART, NAME={pname}")
        for b_pid, etype, conn, start_ge in block_ranges:
            if b_pid != pid:
                continue
            inp_type = CANONICAL_TO_INP[etype]
            lines.append(f"*ELEMENT, TYPE={inp_type}")
            for local_i, row in enumerate(conn):
                eid = start_ge + local_i + 1
                tokens = [str(eid)] + [str(int(n) + 1) for n in row]
                # Wrap long connectivities (e.g. C3D20) safely at <= 16 tokens per line.
                for chunk_start in range(0, len(tokens), 16):
                    chunk = tokens[chunk_start : chunk_start + 16]
                    lines.append(", ".join(chunk))
        lines.append("*END PART")

    for sname, nids in node_sets.items():
        lines.append(f"*NSET, NSET={sname}")
        lines.extend(_wrap_ids(int(n) + 1 for n in nids))

    for sname, eids in elem_sets.items():
        lines.append(f"*ELSET, ELSET={sname}")
        lines.extend(_wrap_ids(int(e) + 1 for e in eids))

    for sname, pairs in model.face_sets.items():
        lines.append(f"*SURFACE, TYPE=ELEMENT, NAME={sname}")
        for ge, lf in pairs:
            if 0 <= ge < len(elem_canon):
                canon = elem_canon[ge]
                snum = _LF_TO_INP_SURFACE.get(canon, {}).get(int(lf))
                if snum is not None:
                    lines.append(f"{ge + 1}, S{snum}")

    if result_fields:
        lines.append("** RESULT FIELDS SUMMARY")
        for fname in sorted(result_fields.keys()):
            lines.append(f"** FIELD={fname}")

    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


__all__ = ["CANONICAL_TO_INP", "write_inp"]
